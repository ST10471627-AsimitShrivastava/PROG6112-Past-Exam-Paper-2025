// I load the product sales and display the calculations.
private void loadProductData() {

    int total = productSales.GetTotalSales();

    double average = productSales.GetAverageSales();

    int overLimit = productSales.GetSalesOverLimit();

    int underLimit = productSales.GetSalesUnderLimit();

    int years = productSales.GetProductsProcessed();

    // I prepare the product sales report.
    String report = String.format(
            java.util.Locale.US,
            "DATA LOG%n%n"
            + "Total Sales: %d%n%n"
            + "Average Sales: %.0f%n%n"
            + "Sales over limit: %d%n%n"
            + "Sales under limit: %d",
            total,
            average,
            overLimit,
            underLimit
    );

    // I display the report in the text area.
    txtProductReport.setText(report);

    // I display the number of years processed.
    lblYearsProcessedValue.setText(String.valueOf(years));
}

// I save the report information to data.txt.
private void saveProductData() {

    // I check whether product data has been loaded.
    if (txtProductReport.getText().trim().isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please load the product data first."
        );

        return;
    }

    try (FileWriter writer = new FileWriter("data.txt")) {

        // I write the report into the text file.
        writer.write(txtProductReport.getText());

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Product data saved successfully."
        );

    } catch (IOException e) {

        // I display a message if the file cannot be saved.
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Unable to save product data."
        );
    }
    
    
}

// I clear the report and years processed label.
private void clearProductData() {

    txtProductReport.setText("");

    lblYearsProcessedValue.setText("");
}
